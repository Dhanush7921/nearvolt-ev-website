"""Generates the original NEARVOLT EV logo set. Wordmark letters are outlined from Unbounded (SIL OFL 1.1)."""
import json, os
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EM, CH, WH = '#19D38F', '#0B0F0E', '#F3F7F5'
PIN = 'M32 61C25.5 52.5 9 42 9 26.5a23 23 0 0 1 46 0C55 42 38.5 52.5 32 61Z'
BOLT = 'M22.5 37.5V17.5L31 28.6 33.4 25.4 41.5 37.5V17.5'
def outline(text, wght, size):
    f = instantiateVariableFont(TTFont(os.path.join(ROOT, 'public/fonts/unbounded-var.woff')), {'wght': wght})
    gs, cmap, hmtx = f.getGlyphSet(), f.getBestCmap(), f['hmtx']
    upm = f['head'].unitsPerEm; s = size / upm; x = 0; pen = SVGPathPen(gs)
    for i, c in enumerate(text):
        g = cmap[ord(c)]
        gs[g].draw(TransformPen(pen, (s, 0, 0, -s, x, 0)))
        x += hmtx[g][0] * s + size * 0.06
    return pen.getCommands(), x - size * 0.06
word, ww = outline('NEARVOLT', 640, 30)
ev, ew = outline('EV', 600, 17)
mark = lambda fill='url(#nvg)', bolt=CH: f'<path d="{PIN}" fill="{fill}"/><path d="{BOLT}" fill="none" stroke="{bolt}" stroke-width="5.2" stroke-linecap="round" stroke-linejoin="round"/>'
grad = f'<defs><linearGradient id="nvg" x1="10" y1="4" x2="54" y2="60" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#5BF0B6"/><stop offset=".55" stop-color="{EM}"/><stop offset="1" stop-color="#0A8F5E"/></linearGradient></defs>'
W = 78 + ww + 12 + ew
def logo(txt):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W:.1f} 64" role="img" aria-label="NEARVOLT EV">{grad}{mark()}'
            f'<g transform="translate(74 43)"><path d="{word}" fill="{txt}"/></g>'
            f'<g transform="translate({74+ww+12:.1f} 43)"><path d="{ev}" fill="{EM}"/></g></svg>')
out = os.path.join(ROOT, 'public/brand'); os.makedirs(out, exist_ok=True)
open(f'{out}/logo-on-dark.svg', 'w').write(logo(WH))
open(f'{out}/logo-on-light.svg', 'w').write(logo(CH))
open(f'{out}/mark.svg', 'w').write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">{grad}{mark()}</svg>')
open(f'{out}/mark-mono.svg', 'w').write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">{mark(CH, WH)}</svg>')
icon = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">{grad}<rect width="64" height="64" rx="14" fill="{CH}"/><g transform="translate(9.6 8.4) scale(.7)">{mark()}</g></svg>'
open(f'{out}/app-icon.svg', 'w').write(icon)
open(os.path.join(ROOT, 'public/favicon.svg'), 'w').write(icon)
open(os.path.join(ROOT, 'src/brand.ts'), 'w').write('// generated by scripts/build_logo.py\nexport const BRAND = ' + json.dumps({'pin': PIN, 'bolt': BOLT, 'word': word, 'wordWidth': round(ww, 2), 'ev': ev, 'evWidth': round(ew, 2)}) + ';\n')
print('ok', round(W, 1))
